def xt_name(display: str, level: int) -> str:
    """展示名 -> QMT 板块名。'食品饮料' + level1 -> 'SW1食品饮料'"""
    return f"SW{level}{display}"


def sector_names(level: int) -> List[str]:
    """取某级别的全部展示名"""
    if level == 1:
        return list(SW_LEVEL_1)
    if level == 2:
        return list(SW_LEVEL_2)
    raise ValueError(f"level 只能是 1 或 2, 收到 {level}")
